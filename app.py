@app.route("/")
def index():
    """Landing page with input form and model descriptions."""
    return render_template("index.html", fields=INPUT_FIELDS)


@app.route("/predict", methods=["POST"])
def predict():
    """
    Accept form input, run both models, return JSON results.
    Called via AJAX from the frontend.
    """
    try:
        # ── Parse input values ─────────────────────────────────
        raw_input = {}
        for field in INPUT_FIELDS:
            name = field["name"]
            val = request.form.get(name, field["default"])
            raw_input[name] = float(val)

        # ── Run Statistical Model ──────────────────────────────
        stat_result = stat_model.predict(raw_input)

        # ── Run XGBoost Model ──────────────────────────────────
        xgb_result = xgb_model.predict(raw_input)

        return jsonify({
            "success": True,
            "statistical": stat_result,
            "xgboost": xgb_result,
            "input": raw_input,
        })

    except Exception as e:
        import traceback
        traceback.print_exc()
        return jsonify({"success": False, "error": str(e)}), 400


